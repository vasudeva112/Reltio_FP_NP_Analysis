"""
Operator evaluators. Operators decide *how* values are combined and how missing
values are treated; the comparator decides whether two values are equal/similar.

Every evaluator returns a LeafResult carrying both the boolean outcome (used by
suspect/automatic groups) and a relevance 0..1 (used by relevance_based groups).
"""

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Sequence, Set, Tuple

from .cleansers import PreparedValues
from .comparators.base import APPROXIMATION, DOCUMENTED, CompareResult, Comparator, EngineContext

ONE_SIDED_NULL = "ONE_SIDED_NULL"
BOTH_NULL = "BOTH_NULL"

# Operator documentation (Sheet 6 / README). "status" is about the operator semantics only.
OPERATOR_DOCS: Dict[str, dict] = {
    "exact": dict(status=DOCUMENTED, nulls="One or both sides without value -> false (relevance 0).",
                  desc="Comparator decides equality; differs from fuzzy only in token generation."),
    "fuzzy": dict(status=DOCUMENTED, nulls="One or both sides without value -> false (relevance 0).",
                  desc="Same comparison as exact; tokens come from the attribute's match token class."),
    "exactOrNull": dict(status=DOCUMENTED, nulls="Equal, OR one side without value, OR both without value -> true.",
                        desc="No tokens generated."),
    "exactOrAllNull": dict(status=DOCUMENTED, nulls="Equal, OR both without value -> true; one-sided null -> false.",
                           desc="No tokens generated by default."),
    "exactOrNullOrAllNull": dict(status=APPROXIMATION,
                                 nulls="Equal, OR one side without value, OR both without value -> true.",
                                 desc="Not found in the Reltio documentation available; evaluated as the union of "
                                      "exactOrNull and exactOrAllNull (= exactOrNull). No tokens generated."),
    "notExactSame": dict(status=APPROXIMATION, nulls="One side without value -> true; both without value -> false.",
                         desc="Inverse of exact (documented as notExact)."),
    "notExact": dict(status=DOCUMENTED, nulls="One side without value -> true; both without value -> false (assumption).",
                     desc="Inverse of exact."),
    "missing": dict(status=APPROXIMATION, nulls="True when both sides have no value.", desc="Not in Reltio docs found."),
    "notMissing": dict(status=APPROXIMATION, nulls="True when both sides have a value.", desc="Not in Reltio docs found."),
    "equals": dict(status=DOCUMENTED, nulls="Entity without value fails.",
                   desc="Each entity must have a value equal (case-insensitive) to one listed value."),
    "in": dict(status=DOCUMENTED, nulls="Entity without value fails.", desc="Same as equals with a value list."),
    "notEquals": dict(status=APPROXIMATION, nulls="Entity without value passes.",
                      desc="Documented: value must not equal listed values (case-insensitive). Multi-value: "
                           "entity fails if ANY value is listed (assumption)."),
    "notIn": dict(status=APPROXIMATION, nulls="Entity without value passes.", desc="Treated as notEquals."),
    "multi": dict(status=DOCUMENTED, nulls="Either side with no value in any member attribute -> false.",
                  desc="Attribute group compared with CrossMultiComparator permutations."),
    "and": dict(status=DOCUMENTED, nulls="-", desc="Boolean: all. Relevance: sum(w*r)/sum(w); logical operands weight 1."),
    "or": dict(status=DOCUMENTED, nulls="-", desc="Boolean: any. Relevance: max(w*r)."),
    "not": dict(status=DOCUMENTED, nulls="-", desc="Boolean: negation. Relevance: 1 - r."),
}
RELEVANCE_NULL_STATUS = APPROXIMATION   # relevance returned by null cases in relevance groups


@dataclass
class LeafResult:
    op: str
    attribute: str
    passed: bool
    relevance: float
    left: str = ""
    right: str = ""
    left_state: str = ""
    right_state: str = ""
    comparator: str = ""
    comparator_status: str = ""
    comparator_params: str = ""
    null_case: str = ""
    matched_values: Tuple[str, str] = ("", "")
    equal_instance_pairs: Set[Tuple[str, str]] = field(default_factory=set)
    permissive_hit: bool = False
    multi_partial: bool = False
    values_differ: bool = False         # both populated, normalised value sets disjoint
    cleanse_notes: Tuple[str, ...] = ()
    detail: str = ""
    excluded: bool = False              # neutral operand (BOTH_NULL_EXACT_MODE=exclude): not in the relevance average
    is_constraint: bool = False
    constraint_left: Optional[bool] = None
    constraint_right: Optional[bool] = None
    status: str = DOCUMENTED            # combined operator/comparator status for this leaf


def _best(cmp: Comparator, left: PreparedValues, right: PreparedValues):
    """Best value pair across multi-values: equal first, then relevance (max relevance documented)."""
    best: Optional[CompareResult] = None
    best_pair = ("", "")
    eq_inst: Set[Tuple[str, str]] = set()
    for l in left.leaves:
        for r in right.leaves:
            res = cmp.compare(l.value, r.value)
            if res.equal:
                eq_inst.add((l.instance, r.instance))
            if best is None or (res.equal, res.relevance) > (best.equal, best.relevance):
                best, best_pair = res, (l.value, r.value)
    return best or CompareResult(False, 0.0), best_pair, eq_inst


def _diagnostics(lr: LeafResult, ctx: EngineContext, cmp: Comparator,
                 left: PreparedValues, right: PreparedValues) -> None:
    nl = {ctx.norm(v) for v in left.values}
    nr = {ctx.norm(v) for v in right.values}
    if nl and nr:
        lr.values_differ = not (nl & nr)
        if lr.passed:
            a, b = lr.matched_values
            lr.permissive_hit = cmp.PERMISSIVE and ctx.norm(a) != ctx.norm(b)
            lr.multi_partial = (len(nl) > 1 or len(nr) > 1) and nl != nr


def evaluate_attribute_op(op: str, attr: str, cmp: Comparator, ctx: EngineContext,
                          left: PreparedValues, right: PreparedValues) -> LeafResult:
    lr = LeafResult(op=op, attribute=attr, passed=False, relevance=0.0,
                    left=left.display(), right=right.display(),
                    left_state=left.state, right_state=right.state,
                    comparator=cmp.RELTIO_NAME, comparator_status=cmp.status,
                    comparator_params=str(cmp.params) if cmp.params else "",
                    cleanse_notes=tuple(dict.fromkeys(left.cleanse_notes + right.cleanse_notes)))
    hl, hr = left.has_value, right.has_value
    op_status = OPERATOR_DOCS.get(op, {}).get("status", APPROXIMATION)

    if not (hl and hr):
        lr.null_case = BOTH_NULL if not (hl or hr) else ONE_SIDED_NULL
        if op in ("exactOrNull", "exactOrNullOrAllNull"):
            lr.passed, lr.relevance = True, 1.0
        elif op == "exactOrAllNull":
            lr.passed = not (hl or hr)
            lr.relevance = 1.0 if lr.passed else 0.0
        elif op in ("notExactSame", "notExact"):
            lr.passed = hl != hr
            lr.relevance = 1.0 if lr.passed else 0.0
        elif op == "missing":
            lr.passed = not (hl or hr)
            lr.relevance = 1.0 if lr.passed else 0.0
        elif op == "notMissing":
            lr.passed, lr.relevance = False, 0.0
        elif op in ("exact", "fuzzy") and lr.null_case == BOTH_NULL and ctx.both_null_exact_mode != "fail":
            lr.passed, lr.relevance = True, 1.0
            lr.excluded = ctx.both_null_exact_mode == "exclude"
            op_status = APPROXIMATION
        lr.detail = lr.null_case + (f" ({ctx.both_null_exact_mode})" if op in ("exact", "fuzzy")
                                    and lr.null_case == BOTH_NULL else "")
        lr.status = op_status
        return lr

    if op in ("missing",):
        lr.passed, lr.relevance, lr.status = False, 0.0, op_status
        return lr
    if op == "notMissing":
        lr.passed, lr.relevance, lr.status = True, 1.0, op_status
        return lr

    res, pair, eq_inst = _best(cmp, left, right)
    lr.matched_values = pair
    lr.detail = res.detail
    if op in ("notExactSame", "notExact"):
        lr.passed = not res.equal
        lr.relevance = 1.0 - res.relevance
    else:
        lr.passed = res.equal
        lr.relevance = res.relevance
        lr.equal_instance_pairs = eq_inst
    lr.status = APPROXIMATION if APPROXIMATION in (op_status, cmp.status) else cmp.status
    _diagnostics(lr, ctx, cmp, left, right)
    return lr


def _constraint_one(op: str, values: Sequence[str], pv: PreparedValues, ctx: EngineContext) -> bool:
    wanted = {ctx.norm(v).lower() for v in values}                 # always case-insensitive (documented)
    have = {ctx.norm(v).lower() for v in pv.values}
    if op in ("equals", "in"):
        return bool(have & wanted)
    return not (have & wanted)                                    # notEquals / notIn


def evaluate_constraint(op: str, attr: str, values: Sequence[str], ctx: EngineContext,
                        left: PreparedValues, right: PreparedValues) -> LeafResult:
    l_ok = _constraint_one(op, values, left, ctx)
    r_ok = _constraint_one(op, values, right, ctx)
    ok = l_ok and r_ok
    return LeafResult(op=op, attribute=attr, passed=ok, relevance=1.0 if ok else 0.0,
                      left=left.display(), right=right.display(),
                      left_state=left.state, right_state=right.state,
                      is_constraint=True, constraint_left=l_ok, constraint_right=r_ok,
                      detail=f"{op} {list(values)}: left={'T' if l_ok else 'F'} right={'T' if r_ok else 'F'}",
                      status=OPERATOR_DOCS.get(op, {}).get("status", APPROXIMATION))


def evaluate_multi(attr: str, members: List[str], group_cmp: Comparator, member_cmps: List[Comparator],
                   ctx: EngineContext, left: List[PreparedValues], right: List[PreparedValues]) -> LeafResult:
    lr = LeafResult(op="multi", attribute=attr, passed=False, relevance=0.0,
                    left=" ; ".join(p.display() for p in left), right=" ; ".join(p.display() for p in right),
                    comparator=group_cmp.RELTIO_NAME, comparator_status=group_cmp.status)
    if not all(p.has_value for p in left) or not all(p.has_value for p in right):
        lr.null_case = ONE_SIDED_NULL if any(p.has_value for p in left + right) else BOTH_NULL
        lr.detail = "member attribute without value"
        return lr
    if hasattr(group_cmp, "compare_groups"):
        res = group_cmp.compare_groups([p.values for p in left], [p.values for p in right], member_cmps)
    else:
        # multi without CrossMultiComparator: positional comparison, all members must match
        rels, eqs = [], []
        for i, cmp in enumerate(member_cmps):
            r, _, _ = _best(cmp, left[i], right[i])
            rels.append(r.relevance)
            eqs.append(r.equal)
        res = CompareResult(all(eqs), sum(rels) / len(rels), "positional")
    lr.passed, lr.relevance, lr.detail = res.equal, res.relevance, res.detail
    statuses = {group_cmp.status} | {c.status for c in member_cmps}
    lr.status = APPROXIMATION if APPROXIMATION in statuses else DOCUMENTED
    lr.permissive_hit = res.equal and "L0->R1" in res.detail
    return lr
